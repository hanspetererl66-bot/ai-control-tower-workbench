-- Agent observability: what the agents, workflows and skills of the Werkbank did at run time.
-- One row per run, one row per step of a run (a trace in the shape of the OpenTelemetry GenAI conventions: invoke_agent, chat,
-- execute_tool, retrieval, approval, guardrail), the results of the regression cases, the alerts and the human review queue.
--
-- Not stored, on purpose: the content of prompts and answers. A step carries its kind, name, system, duration, tokens, cost and a short
-- note (an error type, a policy message). People appear only as a pseudonym ("u-0412"), never as a name or an e-mail address.
--
-- Same pattern as the other work in the shared database: tables closed to anon/authenticated, access through functions for
-- service_role only; the person is the e-mail label (p_actor) until the sign-in is decided (there is no role check yet).
-- Runs and steps are append only (a trigger refuses update and delete); alerts change status, nothing else.
-- The reading functions are at the end. The data comes from migration 037 (generated, fictional) or, later, from the app.

create schema if not exists observability;

create table if not exists observability.agent (
  agent_id text primary key check (agent_id ~ '^[a-z0-9-]{2,60}$'),
  name text not null check (char_length(name) between 1 and 120),
  kind text not null check (kind in ('agent', 'workflow', 'skill')),
  department text not null default '' check (char_length(department) <= 60),
  owner text not null default '' check (char_length(owner) <= 120),
  platform text not null default '' check (char_length(platform) <= 60),
  model text not null default '' check (char_length(model) <= 60),
  version text not null check (char_length(version) between 1 and 20),
  criticality text not null default 'operational' check (criticality in ('administrative', 'operational', 'critical', 'mission-critical')),
  policy_mode text not null default 'read-only' check (policy_mode in ('read-only', 'draft', 'act-after-approval', 'autonomous')),
  writes boolean not null default false,
  unattended boolean not null default false,
  launched_on date,
  retired boolean not null default false
);

create table if not exists observability.run (
  run_id bigint generated by default as identity primary key,
  agent_id text not null references observability.agent (agent_id),
  version text not null,
  started_at timestamptz not null,
  duration_ms integer not null check (duration_ms >= 0),
  -- Time the run waited for a person (approval). Not part of duration_ms, so speed figures describe the agent, not the queue.
  wait_ms integer not null default 0 check (wait_ms >= 0),
  status text not null check (status in ('ok', 'error', 'blocked', 'escalated')),
  trigger_kind text not null check (trigger_kind in ('schedule', 'person', 'event')),
  caller text not null default 'system' check (char_length(caller) <= 20),
  steps integer not null default 0 check (steps >= 0),
  input_tokens integer not null default 0 check (input_tokens >= 0),
  output_tokens integer not null default 0 check (output_tokens >= 0),
  cost_eur numeric(10, 4) not null default 0 check (cost_eur >= 0),
  error_type text not null default '' check (char_length(error_type) <= 40),
  -- Set only on runs that were sampled for quality: a judge score (0 to 1) and the result of the outcome check (the state of the system
  -- after the run against the annotated goal). A green run with goal_met false is a run that looked fine and was wrong.
  quality numeric(3, 2) check (quality is null or quality between 0 and 1),
  goal_met boolean
);
create index if not exists run_started_idx on observability.run (started_at desc);
create index if not exists run_agent_started_idx on observability.run (agent_id, started_at desc);
create index if not exists run_status_idx on observability.run (status, started_at desc);

create table if not exists observability.span (
  run_id bigint not null references observability.run (run_id),
  ord integer not null check (ord >= 1),
  parent_ord integer,
  kind text not null check (kind in ('invoke_agent', 'chat', 'execute_tool', 'retrieval', 'approval', 'guardrail')),
  name text not null check (char_length(name) between 1 and 80),
  system text not null default '' check (char_length(system) <= 40),
  offset_ms integer not null default 0 check (offset_ms >= 0),
  duration_ms integer not null default 0 check (duration_ms >= 0),
  status text not null check (status in ('ok', 'error', 'blocked', 'waiting')),
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  cost_eur numeric(10, 5) not null default 0,
  note text not null default '' check (char_length(note) <= 200),
  primary key (run_id, ord)
);
create index if not exists span_status_idx on observability.span (status) where status in ('blocked', 'error');
create index if not exists span_kind_idx on observability.span (kind);

create table if not exists observability.eval_case (
  case_id text primary key,
  agent_id text not null references observability.agent (agent_id),
  name text not null check (char_length(name) <= 120),
  kind text not null check (kind in ('state', 'schema', 'safety', 'regression', 'quality'))
);

create table if not exists observability.eval_result (
  batch_id text not null,
  case_id text not null references observability.eval_case (case_id),
  attempt integer not null check (attempt >= 1),
  agent_id text not null references observability.agent (agent_id),
  version text not null,
  passed boolean not null,
  ran_at timestamptz not null,
  primary key (batch_id, case_id, attempt)
);
create index if not exists eval_result_agent_idx on observability.eval_result (agent_id, ran_at desc);

create table if not exists observability.alert (
  alert_id bigint generated by default as identity primary key,
  agent_id text references observability.agent (agent_id),
  raised_at timestamptz not null,
  severity text not null check (severity in ('page', 'ticket', 'info')),
  rule text not null check (char_length(rule) <= 60),
  message text not null check (char_length(message) <= 300),
  status text not null default 'open' check (status in ('open', 'acknowledged', 'resolved')),
  resolved_at timestamptz
);
create index if not exists alert_status_idx on observability.alert (status, raised_at desc);

create table if not exists observability.review (
  run_id bigint primary key references observability.run (run_id),
  status text not null default 'pending' check (status in ('pending', 'done')),
  verdict text check (verdict is null or verdict in ('correct', 'wrong')),
  reviewer text not null default '' check (char_length(reviewer) <= 120),
  reviewed_at timestamptz
);

alter table observability.agent enable row level security;
alter table observability.run enable row level security;
alter table observability.span enable row level security;
alter table observability.eval_case enable row level security;
alter table observability.eval_result enable row level security;
alter table observability.alert enable row level security;
alter table observability.review enable row level security;
revoke all on all tables in schema observability from anon, authenticated;

-- Runs and steps are history: nothing may change or remove them.
create or replace function observability.append_only()
returns trigger language plpgsql set search_path = '' as $$
begin
  raise exception 'the run history is append only: a logged run or step cannot be changed or removed';
end $$;
drop trigger if exists run_no_change on observability.run;
create trigger run_no_change before update or delete on observability.run for each row execute function observability.append_only();
drop trigger if exists span_no_change on observability.span;
create trigger span_no_change before update or delete on observability.span for each row execute function observability.append_only();

create or replace function observability.check_actor(p_actor text)
returns void language plpgsql immutable set search_path = '' as $$
begin
  if p_actor is null or p_actor !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'actor must be an e-mail address'; end if;
end $$;

