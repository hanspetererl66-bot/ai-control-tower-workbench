-- Fleet: the numbers on top, the daily series, one row per agent, the week/hour heat map, departments, models and the tools that fail.
create or replace function public.obs_dashboard(p_actor text, p_days integer default 30)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  d integer := least(greatest(coalesce(p_days, 30), 1), 90);
  t0 timestamptz := now() - make_interval(days => least(greatest(coalesce(p_days, 30), 1), 90));
  t1 timestamptz := now() - make_interval(days => 2 * least(greatest(coalesce(p_days, 30), 1), 90));
  kpis jsonb; daily jsonb; agents jsonb; heat jsonb; depts jsonb; models jsonb; tools jsonb; alerts jsonb;
begin
  perform observability.check_actor(p_actor);

  select jsonb_build_object(
    'runs', count(*) filter (where started_at >= t0),
    'prevRuns', count(*) filter (where started_at < t0),
    'okPct', round(100.0 * count(*) filter (where started_at >= t0 and status = 'ok') / nullif(count(*) filter (where started_at >= t0), 0), 1),
    'prevOkPct', round(100.0 * count(*) filter (where started_at < t0 and status = 'ok') / nullif(count(*) filter (where started_at < t0), 0), 1),
    'escalatedPct', round(100.0 * count(*) filter (where started_at >= t0 and status = 'escalated') / nullif(count(*) filter (where started_at >= t0), 0), 1),
    'blocked', count(*) filter (where started_at >= t0 and status = 'blocked'),
    'prevBlocked', count(*) filter (where started_at < t0 and status = 'blocked'),
    'p50ms', (percentile_cont(0.5) within group (order by duration_ms) filter (where started_at >= t0))::integer,
    'p95ms', (percentile_cont(0.95) within group (order by duration_ms) filter (where started_at >= t0))::integer,
    'costEur', round(coalesce(sum(cost_eur) filter (where started_at >= t0), 0), 2),
    'prevCostEur', round(coalesce(sum(cost_eur) filter (where started_at < t0), 0), 2),
    'tokens', coalesce(sum(input_tokens + output_tokens) filter (where started_at >= t0), 0),
    'sampled', count(*) filter (where started_at >= t0 and goal_met is not null),
    'goalPct', round(100.0 * count(*) filter (where started_at >= t0 and goal_met) / nullif(count(*) filter (where started_at >= t0 and goal_met is not null), 0), 1),
    'greenButWrong', count(*) filter (where started_at >= t0 and status = 'ok' and goal_met is false),
    'greenSampled', count(*) filter (where started_at >= t0 and status = 'ok' and goal_met is not null),
    'agentsActive', count(distinct agent_id) filter (where started_at >= t0),
    'callers', count(distinct caller) filter (where started_at >= t0 and caller <> 'system')
  ) into kpis
  from observability.run where started_at >= t1;

  select coalesce(jsonb_agg(x order by x->>'d'), '[]'::jsonb) into daily from (
    select jsonb_build_object('d', g.day, 'runs', coalesce(c.runs, 0), 'ok', coalesce(c.ok, 0), 'error', coalesce(c.err, 0),
             'blocked', coalesce(c.blk, 0), 'escalated', coalesce(c.esc, 0), 'cost', round(coalesce(c.cost, 0), 2), 'p95', coalesce(c.p95, 0)) as x
    from generate_series((now() at time zone 'UTC')::date - (d - 1), (now() at time zone 'UTC')::date, interval '1 day') as g(day)
    left join (
      select (started_at at time zone 'UTC')::date as day, count(*) as runs, count(*) filter (where status = 'ok') as ok,
             count(*) filter (where status = 'error') as err, count(*) filter (where status = 'blocked') as blk,
             count(*) filter (where status = 'escalated') as esc, sum(cost_eur) as cost,
             (percentile_cont(0.95) within group (order by duration_ms))::integer as p95
      from observability.run where started_at >= t0 group by 1
    ) c on c.day = g.day::date
  ) s;

  select coalesce(jsonb_agg(x order by (x->>'runs')::int desc), '[]'::jsonb) into agents from (
    select jsonb_build_object(
      'id', a.agent_id, 'name', a.name, 'kind', a.kind, 'department', a.department, 'owner', a.owner, 'platform', a.platform, 'model', a.model,
      'version', a.version, 'criticality', a.criticality, 'mode', a.policy_mode, 'writes', a.writes, 'unattended', a.unattended, 'retired', a.retired,
      'runs', coalesce(c.runs, 0), 'prevRuns', coalesce(p.runs, 0),
      'okPct', round(100.0 * c.ok / nullif(c.runs, 0), 1), 'prevOkPct', round(100.0 * p.ok / nullif(p.runs, 0), 1),
      'escalatedPct', round(100.0 * c.esc / nullif(c.runs, 0), 1), 'blocked', coalesce(c.blk, 0),
      'p95ms', c.p95, 'costEur', round(coalesce(c.cost, 0), 2), 'callers', coalesce(c.callers, 0),
      'sampled', coalesce(c.sampled, 0), 'goalPct', round(100.0 * c.goal / nullif(c.sampled, 0), 1),
      'quality', c.quality, 'greenButWrong', coalesce(c.gbw, 0), 'lastRun', c.last_run,
      'spark', (select coalesce(jsonb_agg(coalesce(s.n, 0) order by g.day), '[]'::jsonb)
                from generate_series((now() at time zone 'UTC')::date - 13, (now() at time zone 'UTC')::date, interval '1 day') as g(day)
                left join (select (r.started_at at time zone 'UTC')::date as day, count(*) as n from observability.run r
                           where r.agent_id = a.agent_id and r.started_at >= now() - interval '14 days' group by 1) s on s.day = g.day::date)
    ) as x
    from observability.agent a
    left join (
      select agent_id, count(*) as runs, count(*) filter (where status = 'ok') as ok, count(*) filter (where status = 'escalated') as esc,
             count(*) filter (where status = 'blocked') as blk, (percentile_cont(0.95) within group (order by duration_ms))::integer as p95,
             sum(cost_eur) as cost, count(distinct caller) filter (where caller <> 'system') as callers,
             count(*) filter (where goal_met is not null) as sampled, count(*) filter (where goal_met) as goal,
             round(avg(quality), 2) as quality, count(*) filter (where status = 'ok' and goal_met is false) as gbw, max(started_at) as last_run
      from observability.run where started_at >= t0 group by agent_id
    ) c on c.agent_id = a.agent_id
    left join (
      select agent_id, count(*) as runs, count(*) filter (where status = 'ok') as ok
      from observability.run where started_at >= t1 and started_at < t0 group by agent_id
    ) p on p.agent_id = a.agent_id
  ) s;

  select coalesce(jsonb_agg(jsonb_build_object('dow', dow, 'hour', hr, 'runs', n)), '[]'::jsonb) into heat from (
    select extract(isodow from started_at at time zone 'Europe/Berlin')::int as dow, extract(hour from started_at at time zone 'Europe/Berlin')::int as hr, count(*) as n
    from observability.run where started_at >= t0 group by 1, 2
  ) s;

  select coalesce(jsonb_agg(x order by (x->>'costEur')::numeric desc), '[]'::jsonb) into depts from (
    select jsonb_build_object('department', a.department, 'runs', count(*), 'okPct', round(100.0 * count(*) filter (where r.status = 'ok') / count(*), 1),
             'costEur', round(sum(r.cost_eur), 2), 'agents', count(distinct r.agent_id)) as x
    from observability.run r join observability.agent a using (agent_id) where r.started_at >= t0 group by a.department
  ) s;

  select coalesce(jsonb_agg(x order by (x->>'costEur')::numeric desc), '[]'::jsonb) into models from (
    select jsonb_build_object('model', a.model, 'runs', count(*), 'tokens', sum(r.input_tokens + r.output_tokens), 'costEur', round(sum(r.cost_eur), 2)) as x
    from observability.run r join observability.agent a using (agent_id) where r.started_at >= t0 group by a.model
  ) s;

  select coalesce(jsonb_agg(x order by (x->>'errPct')::numeric desc, (x->>'calls')::int desc), '[]'::jsonb) into tools from (
    select jsonb_build_object('system', s.system, 'tool', s.name, 'calls', count(*), 'errors', count(*) filter (where s.status = 'error'),
             'errPct', round(100.0 * count(*) filter (where s.status = 'error') / count(*), 1),
             'p95ms', (percentile_cont(0.95) within group (order by s.duration_ms))::integer) as x
    from observability.span s join observability.run r using (run_id)
    where r.started_at >= t0 and s.kind = 'execute_tool' group by s.system, s.name having count(*) >= 30 order by 1 limit 12
  ) s;

  select jsonb_build_object('page', count(*) filter (where severity = 'page'), 'ticket', count(*) filter (where severity = 'ticket'), 'info', count(*) filter (where severity = 'info'))
    into alerts from observability.alert where status <> 'resolved';

  return jsonb_build_object('days', d, 'asOf', now(), 'kpis', kpis, 'daily', daily, 'agents', agents, 'heat', heat, 'departments', depts, 'models', models, 'tools', tools, 'openAlerts', alerts);
end $$;

-- Run list with filters (newest first). p_before is the run_id of the last row of the previous page.
create or replace function public.obs_runs(p_actor text, p_agent text default null, p_status text default null, p_days integer default 7, p_limit integer default 60, p_before bigint default null, p_min_cost numeric default null)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare lim integer := least(greatest(coalesce(p_limit, 60), 1), 200); res jsonb; total bigint;
begin
  perform observability.check_actor(p_actor);
  select count(*) into total from observability.run r
   where r.started_at >= now() - make_interval(days => least(greatest(coalesce(p_days, 7), 1), 90))
     and (p_agent is null or r.agent_id = p_agent) and (p_status is null or r.status = p_status) and (p_min_cost is null or r.cost_eur >= p_min_cost);
  select coalesce(jsonb_agg(x order by (x->>'id')::bigint desc), '[]'::jsonb) into res from (
    select jsonb_build_object('id', r.run_id, 'agent', r.agent_id, 'name', a.name, 'version', r.version, 'at', r.started_at, 'ms', r.duration_ms, 'waitMs', r.wait_ms, 'status', r.status,
             'trigger', r.trigger_kind, 'caller', r.caller, 'steps', r.steps, 'tokens', r.input_tokens + r.output_tokens, 'costEur', r.cost_eur,
             'error', r.error_type, 'quality', r.quality, 'goalMet', r.goal_met) as x
    from observability.run r join observability.agent a using (agent_id)
    where r.started_at >= now() - make_interval(days => least(greatest(coalesce(p_days, 7), 1), 90))
      and (p_agent is null or r.agent_id = p_agent) and (p_status is null or r.status = p_status)
      and (p_min_cost is null or r.cost_eur >= p_min_cost) and (p_before is null or r.run_id < p_before)
    order by r.run_id desc limit lim
  ) s;
  return jsonb_build_object('total', total, 'runs', res);
end $$;

-- One trace: the run and its steps in order, with the offset of each step so the page can draw the waterfall.
create or replace function public.obs_trace(p_actor text, p_run_id bigint)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare r jsonb; sp jsonb; rv jsonb;
begin
  perform observability.check_actor(p_actor);
  select jsonb_build_object('id', r.run_id, 'agent', r.agent_id, 'name', a.name, 'version', r.version, 'model', a.model, 'mode', a.policy_mode, 'at', r.started_at,
           'ms', r.duration_ms, 'waitMs', r.wait_ms, 'status', r.status, 'trigger', r.trigger_kind, 'caller', r.caller, 'steps', r.steps, 'inTokens', r.input_tokens,
           'outTokens', r.output_tokens, 'costEur', r.cost_eur, 'error', r.error_type, 'quality', r.quality, 'goalMet', r.goal_met)
    into r from observability.run r join observability.agent a using (agent_id) where r.run_id = p_run_id;
  if r is null then raise exception 'run not found'; end if;
  select coalesce(jsonb_agg(jsonb_build_object('ord', ord, 'parent', parent_ord, 'kind', kind, 'name', name, 'system', system, 'offset', offset_ms, 'ms', duration_ms,
           'status', status, 'inTokens', input_tokens, 'outTokens', output_tokens, 'costEur', cost_eur, 'note', note) order by ord), '[]'::jsonb)
    into sp from observability.span where run_id = p_run_id;
  select to_jsonb(v) into rv from (select status, verdict, reviewed_at as "at" from observability.review where run_id = p_run_id) v;
  return jsonb_build_object('run', r, 'spans', sp, 'review', rv);
end $$;

-- Quality: the regression cases (pass rate and pass^k per version), the trend per batch, the gap between "the run was green" and "the outcome was right",
-- and the human review queue. pass^k counts a case only when it passed on every attempt of the batch.
create or replace function public.obs_quality(p_actor text)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare versions jsonb; trend jsonb; failing jsonb; gap jsonb; queue jsonb; review jsonb; latest text;
begin
  perform observability.check_actor(p_actor);
  select batch_id into latest from observability.eval_result order by ran_at desc, batch_id desc limit 1;

  with per_case as (
    select agent_id, version, batch_id, case_id, bool_and(passed) as all_passed, avg(passed::int) as rate, max(ran_at) as ran_at
    from observability.eval_result group by agent_id, version, batch_id, case_id
  )
  select coalesce(jsonb_agg(x order by x->>'agent', x->>'version'), '[]'::jsonb) into versions from (
    select jsonb_build_object('agent', pc.agent_id, 'name', a.name, 'version', pc.version, 'batches', count(distinct pc.batch_id),
             'passRate', round(100 * avg(pc.rate), 1), 'passK', round(100 * avg(pc.all_passed::int), 1), 'since', min(pc.ran_at), 'until', max(pc.ran_at)) as x
    from per_case pc join observability.agent a on a.agent_id = pc.agent_id group by pc.agent_id, a.name, pc.version
  ) s;

  with per_case as (
    select agent_id, version, batch_id, case_id, bool_and(passed) as all_passed, avg(passed::int) as rate, max(ran_at) as ran_at
    from observability.eval_result group by agent_id, version, batch_id, case_id
  )
  select coalesce(jsonb_agg(x order by x->>'batch'), '[]'::jsonb) into trend from (
    select jsonb_build_object('batch', batch_id, 'at', max(ran_at), 'passRate', round(100 * avg(rate), 1), 'passK', round(100 * avg(all_passed::int), 1)) as x
    from per_case group by batch_id
  ) s;

  select coalesce(jsonb_agg(x order by x->>'name'), '[]'::jsonb) into failing from (
    select jsonb_build_object('agent', e.agent_id, 'name', a.name, 'case', c.name, 'kind', c.kind, 'version', e.version,
             'passed', count(*) filter (where e.passed), 'attempts', count(*)) as x
    from observability.eval_result e join observability.eval_case c using (case_id) join observability.agent a on a.agent_id = e.agent_id
    where e.batch_id = latest group by e.agent_id, a.name, c.name, c.kind, e.version having count(*) filter (where e.passed) < count(*)
  ) s;

  select coalesce(jsonb_agg(x order by (x->>'gap')::numeric desc nulls last), '[]'::jsonb) into gap from (
    select jsonb_build_object('agent', a.agent_id, 'name', a.name, 'okPct', round(100.0 * count(*) filter (where r.status = 'ok') / count(*), 1),
             'sampled', count(*) filter (where r.goal_met is not null),
             'goalPct', round(100.0 * count(*) filter (where r.goal_met) / nullif(count(*) filter (where r.goal_met is not null), 0), 1),
             'judge', round(avg(r.quality), 2),
             'greenButWrong', count(*) filter (where r.status = 'ok' and r.goal_met is false),
             'gap', round(100.0 * count(*) filter (where r.status = 'ok') / count(*) - 100.0 * count(*) filter (where r.goal_met) / nullif(count(*) filter (where r.goal_met is not null), 0), 1)) as x
    from observability.run r join observability.agent a using (agent_id)
    where r.started_at >= now() - interval '30 days' group by a.agent_id, a.name having count(*) filter (where r.goal_met is not null) >= 10
  ) s;

  select coalesce(jsonb_agg(x order by (x->>'id')::bigint desc), '[]'::jsonb) into queue from (
    select jsonb_build_object('id', r.run_id, 'agent', a.name, 'at', r.started_at, 'status', r.status, 'quality', r.quality, 'goalMet', r.goal_met, 'costEur', r.cost_eur) as x
    from observability.review v join observability.run r using (run_id) join observability.agent a using (agent_id)
    where v.status = 'pending' order by r.run_id desc limit 25
  ) s;

  select jsonb_build_object('pending', count(*) filter (where v.status = 'pending'), 'done', count(*) filter (where v.status = 'done'),
           'wrong', count(*) filter (where v.verdict = 'wrong'),
           'agreePct', round(100.0 * count(*) filter (where v.status = 'done' and ((v.verdict = 'correct') = r.goal_met)) / nullif(count(*) filter (where v.status = 'done'), 0), 1))
    into review from observability.review v join observability.run r using (run_id);

  return jsonb_build_object('latestBatch', latest, 'versions', versions, 'trend', trend, 'failing', failing, 'gap', gap, 'queue', queue, 'review', review);
end $$;

-- Safety: actions the policy blocked, what is allowed to act alone, guardrail hits and how long approvals wait.
create or replace function public.obs_safety(p_actor text, p_days integer default 30)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare t0 timestamptz := now() - make_interval(days => least(greatest(coalesce(p_days, 30), 1), 90)); blocked jsonb; autonomy jsonb; guard jsonb; appr jsonb; daily jsonb;
begin
  perform observability.check_actor(p_actor);
  select coalesce(jsonb_agg(x order by x->>'at' desc), '[]'::jsonb) into blocked from (
    select jsonb_build_object('run', s.run_id, 'agent', a.name, 'mode', a.policy_mode, 'tool', s.name, 'system', s.system, 'note', s.note, 'at', r.started_at) as x
    from observability.span s join observability.run r using (run_id) join observability.agent a using (agent_id)
    where s.status = 'blocked' and r.started_at >= t0 order by r.started_at desc limit 60
  ) s;
  select coalesce(jsonb_agg(x order by (x->>'runs')::int desc), '[]'::jsonb) into autonomy from (
    select jsonb_build_object('agent', a.agent_id, 'name', a.name, 'mode', a.policy_mode, 'writes', a.writes, 'unattended', a.unattended, 'criticality', a.criticality,
             'runs', count(r.run_id), 'blocked', count(r.run_id) filter (where r.status = 'blocked'), 'escalated', count(r.run_id) filter (where r.status = 'escalated')) as x
    from observability.agent a left join observability.run r on r.agent_id = a.agent_id and r.started_at >= t0
    where not a.retired and (a.writes or a.unattended or a.policy_mode in ('act-after-approval', 'autonomous')) group by a.agent_id
  ) s;
  select coalesce(jsonb_agg(x order by (x->>'hits')::int desc), '[]'::jsonb) into guard from (
    select jsonb_build_object('agent', a.name, 'note', s.note, 'hits', count(*)) as x
    from observability.span s join observability.run r using (run_id) join observability.agent a using (agent_id)
    where s.kind = 'guardrail' and s.note <> '' and r.started_at >= t0 group by a.name, s.note
  ) s;
  select jsonb_build_object('approvals', count(*), 'waitingMin', round(avg(s.duration_ms) / 60000.0, 1), 'p95Min', round((percentile_cont(0.95) within group (order by s.duration_ms) / 60000.0)::numeric, 1),
           'waiting', count(*) filter (where s.status = 'waiting')) into appr
    from observability.span s join observability.run r using (run_id) where s.kind = 'approval' and r.started_at >= t0;
  select coalesce(jsonb_agg(x order by x->>'d'), '[]'::jsonb) into daily from (
    select jsonb_build_object('d', q.day, 'blocked', q.n) as x
    from (select (r.started_at at time zone 'UTC')::date as day, count(*) as n
          from observability.span s join observability.run r using (run_id) where s.status = 'blocked' and r.started_at >= t0 group by 1) q
  ) s;
  return jsonb_build_object('days', least(greatest(coalesce(p_days, 30), 1), 90), 'blocked', blocked, 'autonomy', autonomy, 'guardrails', guard, 'approvals', appr, 'blockedDaily', daily);
end $$;

-- Cost: per day, agent, department and model; the days that stand out; the most expensive runs; a simple month-end estimate (a rule of thumb, not a model).
create or replace function public.obs_cost(p_actor text, p_days integer default 30)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  d integer := least(greatest(coalesce(p_days, 30), 1), 90);
  t0 timestamptz := now() - make_interval(days => least(greatest(coalesce(p_days, 30), 1), 90));
  daily jsonb; by_agent jsonb; top_runs jsonb; spikes jsonb; mtd numeric; last7 numeric; days_left integer; med numeric;
begin
  perform observability.check_actor(p_actor);
  select coalesce(jsonb_agg(x order by x->>'d'), '[]'::jsonb) into daily from (
    select jsonb_build_object('d', q.day, 'cost', round(q.cost, 2), 'runs', q.runs) as x
    from (select (started_at at time zone 'UTC')::date as day, sum(cost_eur) as cost, count(*) as runs from observability.run where started_at >= t0 group by 1) q
  ) s;
  select coalesce(jsonb_agg(x order by (x->>'costEur')::numeric desc), '[]'::jsonb) into by_agent from (
    select jsonb_build_object('agent', a.agent_id, 'name', a.name, 'department', a.department, 'model', a.model, 'runs', count(*), 'costEur', round(sum(r.cost_eur), 2),
             'perRun', round(avg(r.cost_eur), 4),
             'perOkRun', round(sum(r.cost_eur) / nullif(count(*) filter (where r.status = 'ok'), 0), 4),
             'tokens', sum(r.input_tokens + r.output_tokens),
             'wasteEur', round(coalesce(sum(r.cost_eur) filter (where r.status = 'error'), 0), 2)) as x
    from observability.run r join observability.agent a using (agent_id) where r.started_at >= t0 group by a.agent_id
  ) s;
  select coalesce(jsonb_agg(x order by (x->>'costEur')::numeric desc), '[]'::jsonb) into top_runs from (
    select jsonb_build_object('id', r.run_id, 'agent', a.name, 'at', r.started_at, 'status', r.status, 'steps', r.steps, 'costEur', r.cost_eur, 'error', r.error_type) as x
    from observability.run r join observability.agent a using (agent_id) where r.started_at >= t0 order by r.cost_eur desc limit 12
  ) s;
  select percentile_cont(0.5) within group (order by day_cost) into med from (select sum(cost_eur) as day_cost from observability.run where started_at >= t0 group by (started_at at time zone 'UTC')::date) q;
  select coalesce(jsonb_agg(x order by x->>'d'), '[]'::jsonb) into spikes from (
    select jsonb_build_object('d', day, 'costEur', round(c, 2), 'times', round(c / nullif(med, 0), 1)) as x
    from (select (started_at at time zone 'UTC')::date as day, sum(cost_eur) as c from observability.run where started_at >= t0 group by 1) q where c > 2 * med
  ) s;
  select coalesce(sum(cost_eur), 0) into mtd from observability.run where started_at >= date_trunc('month', now());
  select coalesce(sum(cost_eur), 0) into last7 from observability.run where started_at >= now() - interval '7 days';
  days_left := (date_trunc('month', now()) + interval '1 month' - interval '1 day')::date - now()::date;
  return jsonb_build_object('days', d, 'daily', daily, 'agents', by_agent, 'topRuns', top_runs, 'spikes', spikes, 'medianDay', round(coalesce(med, 0), 2),
           'monthToDate', round(mtd, 2), 'estimateMonthEnd', round(mtd + last7 / 7.0 * days_left, 2), 'daysLeft', days_left);
end $$;

-- Alerts, newest first; the counts by rule and severity.
create or replace function public.obs_alerts(p_actor text, p_status text default null)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare rows jsonb; counts jsonb;
begin
  perform observability.check_actor(p_actor);
  select coalesce(jsonb_agg(x order by x->>'at' desc), '[]'::jsonb) into rows from (
    select jsonb_build_object('id', l.alert_id, 'agent', a.name, 'agentId', l.agent_id, 'at', l.raised_at, 'severity', l.severity, 'rule', l.rule, 'message', l.message,
             'status', l.status, 'resolvedAt', l.resolved_at) as x
    from observability.alert l left join observability.agent a using (agent_id) where p_status is null or l.status = p_status
  ) s;
  select jsonb_build_object('open', count(*) filter (where status = 'open'), 'acknowledged', count(*) filter (where status = 'acknowledged'), 'resolved', count(*) filter (where status = 'resolved'),
           'page', count(*) filter (where severity = 'page' and status <> 'resolved'), 'ticket', count(*) filter (where severity = 'ticket' and status <> 'resolved'),
           'info', count(*) filter (where severity = 'info' and status <> 'resolved')) into counts from observability.alert;
  return jsonb_build_object('alerts', rows, 'counts', counts);
end $$;

