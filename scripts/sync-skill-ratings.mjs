/**
 * Skill ratings: writes supabase/migrations/20261019_013_skill_ratings.sql from examples/skill-marketplace/ratings.json
 * (fictional sample ratings, anonymous). The same file is embedded into the Skill Marketplace Space by
 * npm run sync:skill-marketplace.
 *   npm run sync:skill-ratings            write
 *   npm run sync:skill-ratings -- --check fail when the migration is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const RATINGS = 'examples/skill-marketplace/ratings.json';
export const MIGRATION = 'supabase/migrations/20261019_013_skill_ratings.sql';
const q = (v) => `'${String(v).replaceAll("'", "''")}'`;

/** One row per sample rating; comments are attached to the first rows of the same star count. */
export function sampleRows(ratings) {
  const rows = [];
  for (const [skill, r] of Object.entries(ratings.skills)) {
    const left = r.comments.map((c) => ({ ...c }));
    r.distribution.forEach((count, i) => {
      for (let n = 1; n <= count; n++) {
        const at = left.findIndex((c) => c.stars === i + 1);
        const c = at >= 0 ? left.splice(at, 1)[0] : null;
        rows.push({ skill, rater: `sample-${skill}-${i + 1}-${n}`, stars: i + 1, comment: c?.text ?? '', version: c?.version ?? 1, date: c?.date ?? '2026-10-01' });
      }
    });
  }
  return rows;
}

export function buildRatingsSql(ratings) {
  const rows = sampleRows(ratings).map((r) => `  (${q(r.skill)}, ${q(r.rater)}, ${r.stars}, ${q(r.comment)}, ${r.version}, ${q(`${r.date}T10:00:00Z`)})`).join(',\n');
  return `-- Skill ratings: 1 to 5 stars per person and skill, anonymous (fictional sample ratings seeded).
-- GENERATED by scripts/sync-skill-ratings.mjs from examples/skill-marketplace/ratings.json. Do not edit by hand.
-- Safe to run more than once. Only public.skills_ratings() and public.skills_rate() are callable, and only with the server-side secret key.
-- Run after 012 (uses skills.profile_settings and skills.skill).
create schema if not exists skills;
revoke all on schema skills from anon, authenticated;

create table if not exists skills.profile_settings (
  key text primary key,
  value jsonb not null
);
create table if not exists skills.skill_rating (
  id bigint generated always as identity primary key,
  skill text not null,
  rater text not null check (char_length(rater) between 8 and 64),
  stars smallint not null check (stars between 1 and 5),
  comment text not null default '' check (char_length(comment) <= 280),
  skill_version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (skill, rater)
);
create index if not exists skill_rating_skill_idx on skills.skill_rating (skill);
alter table skills.profile_settings enable row level security;
alter table skills.skill_rating enable row level security;
revoke all on skills.skill_rating, skills.profile_settings from anon, authenticated;

insert into skills.profile_settings (key, value) values ('ratings', ${q(JSON.stringify(ratings.settings))}::jsonb)
on conflict (key) do update set value = excluded.value;

-- Fictional sample ratings. Only rows whose rater starts with "sample-" are touched when this file runs again.
insert into skills.skill_rating (skill, rater, stars, comment, skill_version, created_at, updated_at)
select v.skill, v.rater, v.stars, v.comment, v.skill_version, v.at::timestamptz, v.at::timestamptz
from (values
${rows}
) as v(skill, rater, stars, comment, skill_version, at)
on conflict (skill, rater) do update
  set stars = excluded.stars, comment = excluded.comment, skill_version = excluded.skill_version, created_at = excluded.created_at, updated_at = excluded.updated_at;

create or replace function public.skills_ratings()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'settings', coalesce((select value from skills.profile_settings where key = 'ratings'), '{}'::jsonb),
    'skills', coalesce((
      select jsonb_object_agg(g.skill, jsonb_build_object(
        'distribution', jsonb_build_array(g.s1, g.s2, g.s3, g.s4, g.s5),
        'comments', coalesce((
          select jsonb_agg(jsonb_build_object('stars', c.stars, 'text', c.comment, 'version', c.skill_version, 'date', to_char(c.updated_at at time zone 'UTC', 'YYYY-MM-DD')) order by c.updated_at desc, c.id desc)
          from (select * from skills.skill_rating x where x.skill = g.skill and x.comment <> '' order by x.updated_at desc, x.id desc limit 5) c
        ), '[]'::jsonb)))
      from (
        select skill,
          count(*) filter (where stars = 1) as s1, count(*) filter (where stars = 2) as s2, count(*) filter (where stars = 3) as s3,
          count(*) filter (where stars = 4) as s4, count(*) filter (where stars = 5) as s5
        from skills.skill_rating group by skill
      ) g
    ), '{}'::jsonb)
  );
$$;

create or replace function public.skills_rate(p_skill text, p_rater text, p_stars integer, p_comment text default '', p_version integer default 1)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_updated boolean;
  v_dist jsonb;
begin
  if p_stars is null or p_stars < 1 or p_stars > 5 then raise exception 'stars must be between 1 and 5'; end if;
  if p_rater is null or char_length(p_rater) < 8 then raise exception 'rater id is missing'; end if;
  if char_length(coalesce(p_comment, '')) > 280 then raise exception 'comment must be at most 280 characters'; end if;
  if not exists (select 1 from skills.skill where slug = p_skill and status <> 'retired') then
    raise exception 'skill % is not in the registry (publish it first)', p_skill;
  end if;
  insert into skills.skill_rating (skill, rater, stars, comment, skill_version)
  values (p_skill, p_rater, p_stars, coalesce(p_comment, ''), greatest(coalesce(p_version, 1), 1))
  on conflict (skill, rater) do update
    set stars = excluded.stars, comment = excluded.comment, skill_version = excluded.skill_version, updated_at = now()
  returning (xmax <> 0) into v_updated;
  select jsonb_agg(coalesce(c.n, 0) order by s.i) into v_dist
  from generate_series(1, 5) as s(i)
  left join (select stars, count(*) as n from skills.skill_rating where skill = p_skill group by stars) c on c.stars = s.i;
  return jsonb_build_object('skill', p_skill, 'updated', v_updated, 'distribution', v_dist);
end;
$$;

revoke all on function public.skills_ratings() from public, anon, authenticated;
revoke all on function public.skills_rate(text, text, integer, text, integer) from public, anon, authenticated;
grant execute on function public.skills_ratings() to service_role;
grant execute on function public.skills_rate(text, text, integer, text, integer) to service_role;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = buildRatingsSql(JSON.parse(readFileSync(join(ROOT, RATINGS), 'utf8')));
  const path = join(ROOT, MIGRATION);
  let current = '';
  try { current = readFileSync(path, 'utf8'); } catch { /* new file */ }
  if (process.argv.includes('--check')) {
    if (current !== sql) { console.error('Skill ratings migration is out of date — run: npm run sync:skill-ratings'); process.exit(1); }
    console.log('Skill ratings migration is in sync.');
  } else {
    writeFileSync(path, sql);
    console.log(`Wrote ${MIGRATION}`);
  }
}
