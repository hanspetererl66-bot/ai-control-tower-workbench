#!/usr/bin/env node
/**
 * Checks that the demo is complete in a Databricks workspace: every table, view and function of sql/00 to 07 exists,
 * tables and views have the expected columns, tables hold the expected number of rows, and the story numbers come out.
 * The expectations are read from the SQL files themselves, so they cannot drift from what the load creates.
 *
 *   DATABRICKS_HOST=https://dbc-123.cloud.databricks.com DATABRICKS_TOKEN=... DATABRICKS_WAREHOUSE_ID=abc123 \
 *     node scripts/databricks-demo-check.mjs [--catalog my_catalog]
 *   node scripts/databricks-demo-check.mjs --print     # the same check as one SQL text to paste into the SQL editor
 *
 * Reads only. Credentials come from the environment (like the loader).
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { accessToken, readHost } from '../connectors/databricks-bridge/server/index.mjs';
import { runStatement, splitStatements, withCatalog } from './databricks-demo-load.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SQL_DIR = join(ROOT, 'examples/databricks-demo/sql');
const FILES = ['00_setup.sql', '01_tables.sql', '02_seed_finance.sql', '03_seed_ops.sql', '04_seed_scm.sql', '05_views.sql', '06_model_view.sql', '07_functions.sql'];
const CATALOG = 'werkbank_demo';

/** Story numbers the demo relies on: [description, SQL returning one value, expected value as text]. */
export const STORY_CHECKS = [
  ['GR/IR candidates (function, all companies)', `SELECT COUNT(*) FROM {c}.fin.get_grir_accrual_candidates('ALL')`, '12'],
  ['GR/IR to accrue (8 items, EUR)', `SELECT CAST(ROUND(SUM(open_value_eur), 2) AS STRING) FROM {c}.fin.get_grir_accrual_candidates('ALL') WHERE classification = 'ACCRUE'`, '245775.0'],
  ['GR/IR stale for clearing review (EUR)', `SELECT CAST(ROUND(SUM(open_value_eur), 2) AS STRING) FROM {c}.fin.get_grir_accrual_candidates('ALL') WHERE classification = 'STALE_REVIEW'`, '17765.0'],
  ['Intercompany differences (view)', `SELECT COUNT(*) FROM {c}.fin.v_ic_differences`, '3'],
];

/** Read what the SQL files create: objects with their columns, the rows each INSERT loads. */
export function expectedFromSql(dir = SQL_DIR, catalog = CATALOG) {
  const objects = new Map(); // 'schema.name' -> { kind, schema, name, columns, rows }
  for (const file of FILES) {
    for (const statement of splitStatements(withCatalog(readFileSync(join(dir, file), 'utf8'), catalog))) {
      const create = /^CREATE OR REPLACE (TABLE|VIEW|FUNCTION)\s+(\w+)\.(\w+)\.(\w+)/i.exec(statement);
      if (create) {
        const [, kind, , schema, name] = create;
        const columns = [];
        if (kind.toUpperCase() !== 'FUNCTION') {
          const body = /\(\s*\n([\s\S]*?)\n\)/.exec(statement.slice(create[0].length));
          for (const line of (body?.[1] ?? '').split('\n')) {
            const col = /^\s*([a-z_][a-z0-9_]*)\s/i.exec(line);
            if (col) columns.push(col[1].toLowerCase());
          }
        }
        objects.set(`${schema}.${name}`, { kind: kind.toLowerCase(), schema, name, columns, rows: null });
        continue;
      }
      const insert = /^INSERT OVERWRITE TABLE\s+\w+\.(\w+)\.(\w+)\s+VALUES/i.exec(statement);
      if (insert) {
        const object = objects.get(`${insert[1]}.${insert[2]}`);
        if (object) object.rows = statement.split('\n').filter((line) => /^\s*\(/.test(line)).length;
      }
    }
  }
  return [...objects.values()];
}

const q = (text) => `'${String(text).replace(/'/g, "''")}'`;

/** The check as SQL for the editor: structure (one query), then row counts. Rows with status PROBLEM need attention. */
export function buildCheckSql(expected, catalog = CATALOG) {
  const schemas = [...new Set(expected.map((o) => o.schema))].map(q).join(', ');
  const values = expected.map((o) => `  (${q(o.kind)}, ${q(o.schema)}, ${q(o.name)}, ${o.columns.length ? `array(${o.columns.map(q).join(', ')})` : 'array()'})`).join(',\n');
  const counted = expected.filter((o) => o.kind === 'table' && o.rows !== null);
  const counts = counted.map((o) => `SELECT ${q(`${o.schema}.${o.name}`)} AS object, ${o.rows} AS expected_rows, (SELECT COUNT(*) FROM ${catalog}.${o.schema}.${o.name}) AS actual_rows`).join('\nUNION ALL\n');
  return `-- Check of the Databricks demo: run each statement, look at the status column.
-- Generated by: node scripts/databricks-demo-check.mjs --write

-- 1. Structure: every table, view and function exists and has its columns.
WITH expected(kind, schema_name, object_name, expected_columns) AS (VALUES
${values}
),
found_objects AS (
  SELECT table_schema AS schema_name, table_name AS object_name FROM ${catalog}.information_schema.tables WHERE table_schema IN (${schemas})
  UNION ALL
  SELECT routine_schema, routine_name FROM ${catalog}.information_schema.routines WHERE routine_schema IN (${schemas})
),
found_columns AS (
  SELECT table_schema AS schema_name, table_name AS object_name, collect_list(lower(column_name)) AS cols
  FROM ${catalog}.information_schema.columns WHERE table_schema IN (${schemas}) GROUP BY table_schema, table_name
)
SELECT
  e.kind,
  concat(e.schema_name, '.', e.object_name) AS object,
  CASE WHEN o.object_name IS NULL THEN 'PROBLEM: missing'
       WHEN size(array_except(e.expected_columns, coalesce(c.cols, array()))) > 0 THEN 'PROBLEM: columns missing'
       ELSE 'OK' END AS status,
  array_join(array_except(e.expected_columns, coalesce(c.cols, array())), ', ') AS missing_columns
FROM expected e
LEFT JOIN found_objects o ON o.schema_name = e.schema_name AND o.object_name = e.object_name
LEFT JOIN found_columns c ON c.schema_name = e.schema_name AND c.object_name = e.object_name
ORDER BY status DESC, object;

-- 2. Rows: every table holds the rows the load inserts (needs part 1 to be all OK).
SELECT object, expected_rows, actual_rows, CASE WHEN expected_rows = actual_rows THEN 'OK' ELSE 'PROBLEM' END AS status
FROM (
${counts}
)
ORDER BY status DESC, object;

-- 3. Story numbers: what the demo says out loud.
${STORY_CHECKS.map(([name, sql, want]) => `SELECT ${q(name)} AS check_name, ${q(want)} AS expected, CAST((${sql.replaceAll('{c}', catalog)}) AS STRING) AS actual`).join('\nUNION ALL\n')};
`;
}

/** Run the checks one by one, so a missing object does not hide the others. `run(sql)` returns the rows as arrays. */
export async function runChecks(expected, run, catalog = CATALOG) {
  const results = [];
  const note = (area, object, status, detail = '') => results.push({ area, object, status, detail });
  const schemas = [...new Set(expected.map((o) => o.schema))].map(q).join(', ');
  const objects = new Set((await run(`SELECT table_schema, table_name FROM ${catalog}.information_schema.tables WHERE table_schema IN (${schemas})`)).map((r) => `${r[0]}.${r[1]}`));
  for (const r of await run(`SELECT routine_schema, routine_name FROM ${catalog}.information_schema.routines WHERE routine_schema IN (${schemas})`)) objects.add(`${r[0]}.${r[1]}`);
  const columns = new Map();
  for (const r of await run(`SELECT table_schema, table_name, column_name FROM ${catalog}.information_schema.columns WHERE table_schema IN (${schemas})`)) {
    const key = `${r[0]}.${r[1]}`;
    columns.set(key, [...(columns.get(key) ?? []), String(r[2]).toLowerCase()]);
  }
  for (const o of expected) {
    const key = `${o.schema}.${o.name}`;
    if (!objects.has(key)) { note(o.kind, key, 'PROBLEM', 'missing'); continue; }
    const missing = o.columns.filter((c) => !(columns.get(key) ?? []).includes(c));
    note(o.kind, key, missing.length ? 'PROBLEM' : 'OK', missing.length ? `columns missing: ${missing.join(', ')}` : `${o.columns.length || ''}${o.columns.length ? ' columns' : ''}`.trim());
    if (o.kind === 'table' && o.rows !== null && !missing.length) {
      try {
        const actual = Number((await run(`SELECT COUNT(*) FROM ${catalog}.${key}`))[0]?.[0]);
        note('rows', key, actual === o.rows ? 'OK' : 'PROBLEM', `${actual} rows, expected ${o.rows}`);
      } catch (error) {
        note('rows', key, 'PROBLEM', error.message.slice(0, 120));
      }
    }
  }
  for (const [name, sql, want] of STORY_CHECKS) {
    try {
      const actual = String((await run(sql.replaceAll('{c}', catalog)))[0]?.[0]);
      note('story', name, Number(actual) === Number(want) ? 'OK' : 'PROBLEM', `${actual}, expected ${want}`);
    } catch (error) {
      note('story', name, 'PROBLEM', error.message.slice(0, 120));
    }
  }
  return results;
}

export function formatReport(results) {
  const width = Math.max(...results.map((r) => r.object.length));
  const lines = results.map((r) => `${r.status === 'OK' ? 'OK     ' : 'PROBLEM'}  ${r.area.padEnd(8)}${r.object.padEnd(width + 2)}${r.detail}`);
  const bad = results.filter((r) => r.status !== 'OK').length;
  lines.push('', bad ? `${bad} of ${results.length} checks need attention. Missing objects: run the matching SQL file (all-in-one.sql runs 00 to 07), then check again.` : `All ${results.length} checks are OK.`);
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const args = process.argv.slice(2);
  const option = (name, fallback) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : fallback; };
  try {
    const catalog = option('--catalog', CATALOG);
    const expected = expectedFromSql(SQL_DIR, catalog);
    if (args.includes('--print')) { process.stdout.write(buildCheckSql(expected, catalog)); process.exit(0); }
    if (args.includes('--write')) {
      const { writeFileSync } = await import('node:fs');
      writeFileSync(join(SQL_DIR, '98_check.sql'), buildCheckSql(expected, CATALOG));
      console.log('wrote examples/databricks-demo/sql/98_check.sql');
      process.exit(0);
    }
    const warehouseId = process.env.DATABRICKS_WAREHOUSE_ID?.trim();
    if (!warehouseId || !/^[0-9a-f]{8,32}$/i.test(warehouseId)) throw new Error('set DATABRICKS_WAREHOUSE_ID to the id of a SQL warehouse');
    const host = readHost();
    await accessToken(host); // fail early on missing credentials
    const run = async (sql) => (await runStatement(host, warehouseId, sql, { pollMs: 1000 })).result?.data_array ?? [];
    console.log(`Checking catalog ${catalog} on ${host.origin} ...\n`);
    const results = await runChecks(expected, run, catalog);
    console.log(formatReport(results));
    process.exit(results.some((r) => r.status !== 'OK') ? 1 : 0);
  } catch (error) {
    console.error(`check failed: ${error.message}`);
    process.exit(1);
  }
}
