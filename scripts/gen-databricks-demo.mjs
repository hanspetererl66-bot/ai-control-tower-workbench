const literal = (type, value) => {
  if (value === null || value === undefined) return 'NULL';
  if (type === 'n') {
    if (!Number.isFinite(value)) throw new Error(`not a number: ${value}`);
    return String(value);
  }
  if (type === 'd') {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) throw new Error(`not a date: ${value}`);
    return `DATE'${value}'`;
  }
  return `'${String(value).replaceAll("'", "''")}'`;
};

function insert(table) {
  const spec = TABLES[table];
  const rows = spec.rows();
  if (spec.types.length !== rows[0].length) throw new Error(`${table}: ${spec.types.length} types for ${rows[0].length} values`);
  const lines = rows.map((row) => {
    if (row.length !== spec.types.length) throw new Error(`${table}: row has ${row.length} values`);
    return `  (${row.map((value, index) => literal(spec.types[index], value)).join(', ')})`;
  });
  // INSERT OVERWRITE keeps the load repeatable: running a seed file twice gives the same rows, not doubled ones.
  return `INSERT OVERWRITE TABLE ${CATALOG}.${table} VALUES\n${lines.join(',\n')};\n`;
}

const seedFile = (title, tables) => `${BANNER}-- ${title}\n\n${tables.map(insert).join('\n')}`;

/* ---------------- the model view ---------------- */

function modelView() {
  const m = RISK_MODEL;
  const label = (key) => `'${DRIVER_LABELS[key].replaceAll("'", "''")}'`;
  return `${BANNER}-- 06_model_view.sql: the stand-in for a Model Serving endpoint.
-- A transparent logistic score over four features, so the demo is deterministic and every number can be explained.
-- In a real landscape replace this view with ai_query('<your-endpoint>', ...) over the same features: the UC functions
-- that read it (07_functions.sql) and the agent recipes stay unchanged.

CREATE OR REPLACE VIEW ${CATALOG}.scm.v_po_delay_scores (
  po_number COMMENT 'Ten-digit purchase order number.',
  item COMMENT 'Item number.',
  buyer_id COMMENT 'Buyer id.',
  vendor_id COMMENT 'Vendor id.',
  vendor_name COMMENT 'Vendor name.',
  material_description COMMENT 'What is ordered.',
  quantity COMMENT 'Ordered quantity.',
  net_value_eur COMMENT 'Order value in EUR.',
  requested_delivery_date COMMENT 'Date the business asked for.',
  confirmed_delivery_date COMMENT 'Date the vendor confirmed.',
  delay_probability COMMENT 'Probability of a late delivery, 0 to 1. Above 0.6 is high risk.',
  expected_delay_days COMMENT 'Expected delay in days.',
  top_drivers COMMENT 'The two largest reasons for the score, separated by semicolons.'
)
COMMENT 'Delay-risk score for every open purchase order. Logistic model: ${m.intercept} + ${m.otifWeight} x (${m.otifReference} - vendor on-time-in-full) + ${m.confirmGapWeight} x days confirmed late + ${m.loadWeight} x max(order size / vendor capacity - ${m.loadReference}, 0) + ${m.laneWeight} x lane backlog.'
AS
WITH features AS (
  SELECT
    p.po_number,
    p.item,
    p.buyer_id,
    p.vendor_id,
    p.vendor_name,
    p.material_description,
    p.quantity,
    p.net_value_eur,
    p.requested_delivery_date,
    p.confirmed_delivery_date,
    CAST(v.otif_90d AS DOUBLE) AS otif_90d,
    CAST(p.days_confirmed_after_requested AS DOUBLE) AS confirm_gap_days,
    CAST(p.quantity AS DOUBLE) / v.monthly_capacity_units AS load_ratio,
    CAST(p.lane_congested AS DOUBLE) AS lane_congested
  FROM ${CATALOG}.scm.purchase_orders p
  JOIN ${CATALOG}.scm.vendors v ON v.vendor_id = p.vendor_id
  WHERE p.status IN ('OPEN', 'PARTIALLY_DELIVERED')
),
contributions AS (
  SELECT
    f.*,
    ${m.otifWeight} * (${m.otifReference} - otif_90d) AS c_otif,
    ${m.confirmGapWeight} * confirm_gap_days AS c_gap,
    ${m.loadWeight} * greatest(load_ratio - ${m.loadReference}, 0) AS c_load,
    ${m.laneWeight} * lane_congested AS c_lane
  FROM features f
),
scored AS (
  SELECT c.*, 1 / (1 + exp(-(${m.intercept} + c_otif + c_gap + c_load + c_lane))) AS probability
  FROM contributions c
)
SELECT
  po_number,
  item,
  buyer_id,
  vendor_id,
  vendor_name,
  material_description,
  quantity,
  net_value_eur,
  requested_delivery_date,
  confirmed_delivery_date,
  round(probability, 3) AS delay_probability,
  round(probability * ${m.expectedDelayScale}, 1) AS expected_delay_days,
  array_join(
    transform(
      slice(
        sort_array(
          filter(
            array(
              named_struct('score', c_otif, 'label', ${label('otif')}),
              named_struct('score', c_gap, 'label', ${label('gap')}),
              named_struct('score', c_load, 'label', ${label('load')}),
              named_struct('score', c_lane, 'label', ${label('lane')})
            ),
            x -> x.score > 0
          ),
          false
        ),
        1,
        2
      ),
      x -> x.label
    ),
    '; '
  ) AS top_drivers
FROM scored;
`;
}

