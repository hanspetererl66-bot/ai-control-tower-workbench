/**
 * Corpus documents of the knowledge feeder, in the format of the other Cognee corpora: short plain text that ends with
 * its identifier in parentheses, for example (sap-docs:btp-integration-suite/docs/xyz.md#chunk-3).
 * Every document carries source, title, URL, license, revision and attribution as plain lines.
 */
import { createHash } from 'node:crypto';
import { SourceBlockedError } from './registry.mjs';

const oneLine = (v, max = 300) => String(v ?? '').replace(/\s+/g, ' ').trim().slice(0, max);
export const shortHash = (v) => createHash('sha1').update(String(v)).digest('hex').slice(0, 12);

/** One chunk of a git source (full text). Only an `allowed` source can build one. */
export function chunkDocument(source, { repo, path, title, heading, text, url, license, revision, attribution, n }) {
  if (source.status !== 'allowed') throw new SourceBlockedError(source, 'full text may not be stored');
  if (!attribution) throw new Error(`A document of ${source.id} needs an attribution line.`);
  const id = `${source.id_prefix}:${repo}/${path}#chunk-${n}`;
  const body = [
    `${oneLine(title, 200)}${heading && heading !== title ? ` > ${oneLine(heading.replace(`${title} > `, ''), 200)}` : ''}`,
    '',
    text.trim(),
    '',
    `Source: ${source.id}`,
    `Title: ${oneLine(title, 200)}`,
    `URL: ${url}`,
    `License: ${license}`,
    `Revision: ${oneLine(revision, 40)}`,
    `Attribution: ${oneLine(attribution, 500)}`,
    `(${id})`,
  ].join('\n');
  return { id, name: oneLine(`${title}${heading && heading !== title ? ` – ${heading.split(' > ').pop()}` : ''}`, 160), text: body, source: source.id };
}

/**
 * One feed item of a metadata_only source. Takes a closed set of fields and nothing else: a body, summary or
 * content field is not accepted, so no article text can reach the corpus through this function.
 */
export function metadataDocument(source, item) {
  if (source.status !== 'metadata_only') throw new SourceBlockedError(source, 'not a metadata_only source');
  const allowed = new Set(['guid', 'title', 'url', 'date', 'categories', 'language', 'feed']);
  const extra = Object.keys(item).filter((k) => !allowed.has(k));
  if (extra.length) throw new Error(`Metadata document of ${source.id} got fields that are not metadata: ${extra.join(', ')}`);
  const id = `${source.id_prefix}:${shortHash(item.guid || item.url)}`;
  const cats = (item.categories ?? []).map((c) => oneLine(c, 60)).filter(Boolean).slice(0, 12);
  const body = [
    `${oneLine(item.title, 200)} (a pointer to a post, no text stored)`,
    `Source: ${source.id}`,
    `Title: ${oneLine(item.title, 200)}`,
    `URL: ${oneLine(item.url, 400)}`,
    item.date ? `Published: ${oneLine(item.date, 40)}` : '',
    cats.length ? `Categories: ${cats.join(', ')}` : '',
    item.language ? `Language: ${oneLine(item.language, 20)}` : '',
    `Fetched from: ${oneLine(item.feed, 300)}`,
    `Attribution: ${oneLine(source.attribution_text.replace('{url}', item.url), 300)}`,
    `(${id})`,
  ].filter((l) => l !== '').join('\n');
  return { id, name: oneLine(item.title, 160), text: body, source: source.id };
}

/** ATTRIBUTION.md from the registry, for the sources that were actually ingested (a list of {source, repos}). */
export function attributionMarkdown(ingested, now = new Date()) {
  const lines = ['# Attribution', '', `Generated by the knowledge feeder on ${now.toISOString().slice(0, 10)}. Not legal advice; see docs/knowledge-feeder.md.`, ''];
  if (!ingested.length) lines.push('Nothing was ingested yet.');
  for (const { source, repos } of ingested) {
    lines.push(`## ${source.title} (${source.id})`, '', `- Status: ${source.status}`, `- Terms: ${source.terms_url}`, `- Dataset: ${source.dataset}`);
    if (repos?.length) {
      lines.push('- Repositories:');
      for (const r of repos) lines.push(`  - ${r.name}: ${r.url}, ${r.license}${r.copyright ? `, ${r.copyright}` : ''}, revision ${r.revision}`);
    }
    if (source.status === 'metadata_only') lines.push('- Only title, URL, date, categories and language are stored. No article or post text.');
    else lines.push('- Content was converted to plain text and split into chunks; it is otherwise unchanged. The license text is in each repository.');
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

/** Rough size of a corpus: the number of documents and an estimate of tokens (about 4 characters each). No model is called. */
export function estimate(docs) {
  const chars = docs.reduce((n, d) => n + d.text.length, 0);
  return { documents: docs.length, characters: chars, tokens: Math.ceil(chars / 4) };
}
