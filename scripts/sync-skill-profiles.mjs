/**
 * Skill profiles (impact, governance, lifecycle, discovery), process gaps and skill requests.
 * examples/skill-marketplace/profiles.json is the single source. This script writes the Supabase migration that
 * creates and seeds the same data; `npm run sync:skill-marketplace` embeds it into the Space. Fictional sample data.
 *   npm run sync:skill-profiles            write the migration
 *   npm run sync:skill-profiles -- --check fail when it is out of date
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PROFILES = 'examples/skill-marketplace/profiles.json';
export const MIGRATION = 'supabase/migrations/20261019_012_skill_profiles.sql';

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const n = (v) => (v === null || v === undefined ? 'null' : String(Number(v)));
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const upsert = (table, key, cols, rows) =>
  `insert into ${table} (${cols.join(', ')}) values\n${rows.map((r) => `  (${r.join(', ')})`).join(',\n')}\non conflict (${key}) do update set\n${cols.filter((c) => c !== key).map((c) => `  ${c} = excluded.${c}`).join(',\n')};\n`;

export function buildProfilesSql(src) {
  const profiles = Object.entries(src.profiles);
  return `-- Skill marketplace profiles: impact, governance, lifecycle, discovery, plus process gaps and skill requests (fictional sample data).
-- GENERATED by scripts/sync-skill-profiles.mjs from examples/skill-marketplace/profiles.json. Do not edit by hand.
-- Safe to run more than once. Only public.skills_profiles() is callable, and only with the server-side secret key.
create schema if not exists skills;
revoke all on schema skills from anon, authenticated;

create table if not exists skills.skill_profile (
  slug text primary key,
  impact jsonb not null default '{}'::jsonb,
  governance jsonb not null default '{}'::jsonb,
  lifecycle jsonb not null default '{}'::jsonb,
  discovery jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists skills.process_gap (
  id text primary key,
  process text not null,
  board_area text not null,
  team text not null default '',
  priority text not null check (priority in ('Low','Medium','High')),
  pain_level int not null check (pain_level between 1 and 5),
  minutes_per_month int not null default 0,
  status text not null check (status in ('No skill','Skill requested','Skill in build')),
  note text not null default ''
);
create table if not exists skills.skill_request (
  id text primary key,
  title text not null,
  requester text not null default '',
  board_area text not null default '',
  votes int not null default 0,
  status text not null check (status in ('Open','Planned','In build','Done','Rejected')),
  created_on date not null default current_date,
  note text not null default ''
);
create table if not exists skills.profile_settings (
  key text primary key,
  value jsonb not null
);
alter table skills.skill_profile enable row level security;
alter table skills.process_gap enable row level security;
alter table skills.skill_request enable row level security;
alter table skills.profile_settings enable row level security;
revoke all on skills.skill_profile, skills.process_gap, skills.skill_request, skills.profile_settings from anon, authenticated;

${upsert('skills.skill_profile', 'slug', ['slug', 'impact', 'governance', 'lifecycle', 'discovery'], profiles.map(([slug, p]) => [q(slug), j(p.impact), j(p.governance), j(p.lifecycle), j(p.discovery)]))}
${upsert('skills.process_gap', 'id', ['id', 'process', 'board_area', 'team', 'priority', 'pain_level', 'minutes_per_month', 'status', 'note'], src.processGaps.map((g) => [q(g.id), q(g.process), q(g.boardArea), q(g.team), q(g.priority), n(g.painLevel), n(g.minutesPerMonth), q(g.status), q(g.note)]))}
${upsert('skills.skill_request', 'id', ['id', 'title', 'requester', 'board_area', 'votes', 'status', 'created_on', 'note'], src.requests.map((r) => [q(r.id), q(r.title), q(r.requester), q(r.boardArea), n(r.votes), q(r.status), q(r.createdOn), q(r.note)]))}
${upsert('skills.profile_settings', 'key', ['key', 'value'], [[q('assumptions'), j(src.assumptions)]])}
create or replace function public.skills_profiles()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'assumptions', coalesce((select value from skills.profile_settings where key = 'assumptions'), '{}'::jsonb),
    'profiles', coalesce((select jsonb_object_agg(p.slug, jsonb_build_object('impact', p.impact, 'governance', p.governance, 'lifecycle', p.lifecycle, 'discovery', p.discovery)) from skills.skill_profile p), '{}'::jsonb),
    'processGaps', coalesce((select jsonb_agg(jsonb_build_object('id', g.id, 'process', g.process, 'boardArea', g.board_area, 'team', g.team, 'priority', g.priority, 'painLevel', g.pain_level, 'minutesPerMonth', g.minutes_per_month, 'status', g.status, 'note', g.note) order by g.id) from skills.process_gap g), '[]'::jsonb),
    'requests', coalesce((select jsonb_agg(jsonb_build_object('id', r.id, 'title', r.title, 'requester', r.requester, 'boardArea', r.board_area, 'votes', r.votes, 'status', r.status, 'createdOn', to_char(r.created_on, 'YYYY-MM-DD'), 'note', r.note) order by r.id) from skills.skill_request r), '[]'::jsonb)
  );
$$;

revoke all on function public.skills_profiles() from public, anon, authenticated;
grant execute on function public.skills_profiles() to service_role;
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const sql = buildProfilesSql(JSON.parse(readFileSync(join(ROOT, PROFILES), 'utf8')));
  const path = join(ROOT, MIGRATION);
  let current = '';
  try { current = readFileSync(path, 'utf8'); } catch { /* new file */ }
  if (process.argv.includes('--check')) {
    if (current !== sql) { console.error('Skill profile migration is out of date — run: npm run sync:skill-profiles'); process.exit(1); }
    console.log('Skill profile migration is in sync.');
  } else {
    writeFileSync(path, sql);
    console.log(`Wrote ${MIGRATION}`);
  }
}
